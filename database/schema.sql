CREATE TABLE IF NOT EXISTS users (
  id BIGSERIAL PRIMARY KEY,
  display_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'USER' CHECK(role IN ('USER','ADMIN')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS nodes (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, type TEXT NOT NULL CHECK (type IN ('TANK','AREA')),
  capacity NUMERIC(12,2) NOT NULL DEFAULT 0, current_level NUMERIC(12,2) NOT NULL DEFAULT 0,
  demand NUMERIC(12,2) NOT NULL DEFAULT 0, available_water NUMERIC(12,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS pipelines (
  id BIGSERIAL PRIMARY KEY, source_id TEXT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  destination_id TEXT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE, distance NUMERIC(12,2) NOT NULL CHECK (distance >= 0),
  capacity NUMERIC(12,2) NOT NULL DEFAULT 0, status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','FAILED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), CHECK(source_id <> destination_id)
);
CREATE TABLE IF NOT EXISTS leaks (
  id BIGSERIAL PRIMARY KEY, pipeline_id BIGINT REFERENCES pipelines(id) ON DELETE SET NULL,
  reporter_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  location TEXT NOT NULL, description TEXT NOT NULL, severity SMALLINT NOT NULL CHECK(severity BETWEEN 1 AND 5),
  estimated_loss NUMERIC(12,2) NOT NULL DEFAULT 0, reporter TEXT NOT NULL DEFAULT 'Public user',
  status TEXT NOT NULL DEFAULT 'REPORTED' CHECK(status IN ('REPORTED','UNDER REVIEW','IN PROGRESS','RESOLVED','REJECTED')),
  resolution_note TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), resolved_at TIMESTAMPTZ
);
